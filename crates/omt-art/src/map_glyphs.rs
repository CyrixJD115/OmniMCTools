//! 16×16 monochrome glyphs for the map screens' Photoshop-style tool
//! rails (Map Viewer + Pruner) and the viewer's panel tabs. Drawn as
//! `#`/`.` grids so every rail button shares one stroke weight and size;
//! `icons::glyph` tints them.

use crate::icons::Glyph;

/// The art grid of a map glyph (`None` for the procedural UI glyphs).
pub(crate) fn art(g: Glyph) -> Option<&'static [&'static str; 16]> {
    Some(match g {
        Glyph::ZoomIn => &ZOOM_IN,
        Glyph::ZoomOut => &ZOOM_OUT,
        Glyph::Fit => &FIT,
        Glyph::SelBox => &SEL_BOX,
        Glyph::SelCircle => &SEL_CIRCLE,
        Glyph::SelPolygon => &SEL_POLYGON,
        Glyph::SelSplit => &SEL_SPLIT,
        Glyph::Clock => &CLOCK,
        Glyph::ChunkGrid => &CHUNK_GRID,
        Glyph::RegionGrid => &REGION_GRID,
        Glyph::Spawn => &SPAWN,
        Glyph::Player => &PLAYER,
        Glyph::Bookmark => &BOOKMARK,
        Glyph::Entity => &ENTITY,
        Glyph::Slime => &SLIME,
        Glyph::Cave => &CAVE,
        Glyph::Slicer => &SLICER,
        Glyph::Texture => &TEXTURE,
        Glyph::Compass => &COMPASS,
        Glyph::Sun => &SUN,
        Glyph::Eye => &EYE,
        Glyph::Contrast => &CONTRAST,
        Glyph::Layers => &LAYERS,
        _ => return None,
    })
}

